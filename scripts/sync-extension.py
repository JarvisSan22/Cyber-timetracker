#!/usr/bin/env python3
"""Copy the tracker's shared look into the Cyber Miner extension, so app/ stays the one source.

- app/static/app.css            -> extension/styles/tracker.css (font URLs rewritten)
- app/static/vendor (Pico, augmented-ui, fonts + licenses) -> extension/vendor/
- THEMES in app/config.py       -> extension/shared/themes.json

Run from the repo root with the app's virtualenv after changing any of them:
    .venv/bin/python scripts/sync-extension.py
"""

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.config import DEFAULT_THEME, FONT_SETS, THEMES, ink_for  # noqa: E402

STATIC = ROOT / "app" / "static"
EXT = ROOT / "extension"
VENDOR_FILES = ("pico.min.css", "augmented-ui.min.css")


def sync_css() -> None:
    css = (STATIC / "app.css").read_text()
    header = "/* GENERATED by scripts/sync-extension.py from app/static/app.css. Edit that file, not this one. */\n"
    out = EXT / "styles" / "tracker.css"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header + css.replace('url("vendor/', 'url("../vendor/'))
    print(f"  {out.relative_to(ROOT)}")


def sync_vendor() -> None:
    dest = EXT / "vendor"
    (dest / "fonts").mkdir(parents=True, exist_ok=True)
    for name in VENDOR_FILES:
        shutil.copy2(STATIC / "vendor" / name, dest / name)
    for font in (STATIC / "vendor" / "fonts").iterdir():
        shutil.copy2(font, dest / "fonts" / font.name)
    print(f"  {dest.relative_to(ROOT)}/ ({len(VENDOR_FILES)} files + fonts)")


def sync_themes() -> None:
    themes = {}
    for name, preset in THEMES.items():
        colors = preset["colors"]
        themes[name] = {
            "label": preset["label"],
            "scheme": preset["scheme"],
            # Same keys as GET /api/theme "vars", so the extension handles both the same way.
            "vars": colors
            | {"accent-ink": ink_for(colors["accent"]), "danger-ink": ink_for(colors["danger"])}
            | FONT_SETS[preset["fonts"]],
        }
    out = EXT / "shared" / "themes.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"default": DEFAULT_THEME, "themes": themes}, ensure_ascii=False, indent=2) + "\n")
    print(f"  {out.relative_to(ROOT)} ({len(themes)} themes)")


def main() -> None:
    print("Syncing tracker look into extension/:")
    sync_css()
    sync_vendor()
    sync_themes()


if __name__ == "__main__":
    main()
